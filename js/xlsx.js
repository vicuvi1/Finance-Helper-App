// Minimal Excel (.xlsx) writer, no dependencies: a zip (stored, not
// compressed) of a few SpreadsheetML files. Supports text, numbers, dates,
// formulas, bold header row, column widths, frozen header and filters.
//
// A sheet is { name, cols: [widths], rows: [[cell, ...], ...] } where a cell
// is a string, a number, null, or { v, t: 'date' | 'money' | 'text', f, bold }.

const enc = new TextEncoder();
const xml = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]))
  // Characters XML 1.0 does not allow.
  .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, ''); // eslint-disable-line no-control-regex

const STYLE = { normal: 0, header: 1, date: 2, money: 3, moneyBold: 4, bold: 5 };

function colName(i) {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

// Excel stores dates as days since 1899-12-30.
export function excelDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return Date.UTC(y, m - 1, d) / 864e5 + 25569;
}

export function safeSheetName(name, used = new Set()) {
  let base = String(name).replace(/[[\]:*?/\\]/g, ' ').trim().slice(0, 31) || 'Sheet';
  let n = base;
  for (let i = 2; used.has(n.toLowerCase()); i++) n = `${base.slice(0, 28)} ${i}`;
  used.add(n.toLowerCase());
  return n;
}

function cellXML(cell, ref, isHeader) {
  if (cell == null || cell === '') return '';
  const c = typeof cell === 'object' ? cell : { v: cell };
  let s = isHeader ? STYLE.header : STYLE.normal;
  if (c.t === 'date') s = STYLE.date;
  else if (c.t === 'money') s = c.bold ? STYLE.moneyBold : STYLE.money;
  else if (c.bold) s = STYLE.bold;
  const sAttr = s ? ` s="${s}"` : '';
  if (c.f) return `<c r="${ref}"${sAttr}><f>${xml(c.f)}</f>${c.v != null ? `<v>${Number(c.v)}</v>` : ''}</c>`;
  if (c.t === 'date') return `<c r="${ref}"${sAttr}><v>${excelDate(c.v)}</v></c>`;
  if (typeof c.v === 'number' && c.t !== 'text') return `<c r="${ref}"${sAttr}><v>${c.v}</v></c>`;
  return `<c r="${ref}"${sAttr} t="inlineStr"><is><t xml:space="preserve">${xml(c.v)}</t></is></c>`;
}

function sheetXML(sheet) {
  const width = Math.max(1, ...sheet.rows.map((r) => r.length));
  const rows = sheet.rows.map((r, i) => `<row r="${i + 1}">${r.map((cell, j) => cellXML(cell, `${colName(j)}${i + 1}`, i === 0 && sheet.header !== false)).join('')}</row>`).join('');
  const cols = (sheet.cols || []).map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const frozen = sheet.header !== false
    ? '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
    : '<sheetViews><sheetView workbookViewId="0"/></sheetViews>';
  const filter = sheet.filterRows ? `<autoFilter ref="A1:${colName(width - 1)}${sheet.filterRows + 1}"/>` : '';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">${frozen}${cols ? `<cols>${cols}</cols>` : ''}<sheetData>${rows}</sheetData>${filter}</worksheet>`;
}

